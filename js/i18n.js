const KEY = "patinoire_lang";

export function getLang() {
  try { return localStorage.getItem(KEY) === "en" ? "en" : "fr"; } catch { return "fr"; }
}

export function setLang(lang) {
  try { localStorage.setItem(KEY, lang); } catch { /* private mode */ }
}

export function t(key, vars = {}) {
  const s = STRINGS[getLang()][key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

export function locale() {
  return getLang() === "en" ? "en-CA" : "fr-CA";
}

export function fmtDate(iso, opts = { dateStyle: "long" }) {
  return new Date(iso).toLocaleString(locale(), opts);
}

// Fills every [data-i18n] element's text
export function applyStatic(root = document) {
  document.documentElement.lang = getLang();
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
}
